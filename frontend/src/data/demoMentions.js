export const demoMentions = seedMentions;

// Generates clearly-labelled local demo conversations for any search term.
// This keeps the frontend useful without pretending to fetch real social-media data.
export function generateDemoMentions(keyword) {
  const cleanKeyword = keyword.trim();
  if (!cleanKeyword) return seedMentions;

  return templates.map((template, index) => ({
    id: `search-${cleanKeyword.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-${index}`,
    platform: template.platform,
    keyword: cleanKeyword,
    author: template.author,
    username: template.username,
    content: template.build(cleanKeyword),
    publishedAt: template.publishedAt,
    updatedAt: "",
    sourceUrl: template.sourceUrl,
    contextTitle: `${template.contextTitle} · Demo result`,
    sentiment: template.sentiment,
    topic: `${cleanKeyword} · ${template.topic}`,
  }));
}
